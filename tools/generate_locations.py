"""Generate Flutter constants from the same catalog the server seeds."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
rows = json.loads((root / 'assets/data/campus_locations.json').read_text())
header = '''// Generated by python3 tools/generate_locations.py. Edit the shared JSON catalog.
// Distances/offsets are coarse demo estimates, not walking routes or surveyed data.
class CampusLocation {
  const CampusLocation(this.id, this.name, this.distanceFromUnionMiles,
      {this.demoXMiles = 0, this.demoYMiles = 0, this.category = 'campus'});
  final String id;
  final String name;
  final double distanceFromUnionMiles;
  final double demoXMiles;
  final double demoYMiles;
  final String category;
}

const campusLocations = <CampusLocation>[
'''
for row in rows:
    header += "  CampusLocation(%s, %s, %s, demoXMiles: %s, demoYMiles: %s, category: %s),\n" % (
        json.dumps(row['id']), json.dumps(row['name'],ensure_ascii=False), row['distanceFromUnionMiles'],
        row['demoXMiles'], row['demoYMiles'], json.dumps(row['category']))
header += '];\n'
(root / 'lib/constants/campus_locations.dart').write_text(header)
